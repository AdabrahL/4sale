// Helper function to get all cities in a region
export const getCitiesByRegion = (regionName) => {
  return Object.values(GHANA_CITIES).filter(city => city.region === regionName);
};

// Helper function to get region data
export const getRegionData = (regionName) => {
  return GHANA_REGIONS[regionName] || null;
};

// Helper function to get city data
export const getCityData = (cityName) => {
  return GHANA_CITIES[cityName] || null;
};

// Helper function to search locations
export const searchLocations = (query) => {
  const lowerQuery = query.toLowerCase();
  const cities = Object.values(GHANA_CITIES).filter(city => 
    city.name.toLowerCase().includes(lowerQuery)
  );
  const regions = Object.values(GHANA_REGIONS).filter(region =>
    region.name.toLowerCase().includes(lowerQuery)
  );
  return { cities, regions };
};

// Export organized location structure for dropdowns
export const GHANA_LOCATIONS_ORGANIZED = Object.entries(GHANA_REGIONS).reduce((acc, [regionKey, regionData]) => {
  acc[regionKey] = {
    ...regionData,
    cities: getCitiesByRegion(regionKey).map(city => city.name)
  };
  return acc;
}, {});
